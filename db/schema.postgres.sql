-- Official claim sentences, kept verbatim so the agent quotes approved copy instead of inventing claims.
CREATE TABLE product_claims (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id     BIGINT NOT NULL REFERENCES products(id),
  claim_th       TEXT NOT NULL,
  claim_en       TEXT,                            -- DERIVED translation
