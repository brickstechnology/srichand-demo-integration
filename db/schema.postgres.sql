-- ───────────────────────────── 2. INGREDIENTS ─────────────────────────────
CREATE TABLE ingredients (                        -- curated cosmetic-science dictionary
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inci_name          TEXT NOT NULL UNIQUE,
  common_name        TEXT,
  name_th            TEXT,
  ingredient_class   TEXT NOT NULL,               -- humectant, retinoid, uv_filter, vitamin_c, aha, bha, peptide, ceramide, emollient, soothing, brightener, absorbent, fragrance, preservative, solvent, other
  what_it_does_en    TEXT,
  what_it_does_th    TEXT,
  evidence_level     TEXT CHECK (evidence_level IN ('strong','moderate','emerging','cosmetic_only') OR evidence_level IS NULL),
  caution_en         TEXT,
  is_uv_filter       BOOLEAN NOT NULL DEFAULT FALSE,
  uv_coverage        TEXT,                        -- 'UVB', 'UVA1', 'UVA+UVB' …
  is_potential_irritant BOOLEAN NOT NULL DEFAULT FALSE,
  is_fragrance       BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE product_ingredients (
  product_id      BIGINT NOT NULL REFERENCES products(id),
  position        INTEGER NOT NULL,               -- order on the INCI list; 1 = highest concentration
  ingredient_id   BIGINT REFERENCES ingredients(id),   -- NULL if not yet in the dictionary
  inci_as_listed  TEXT NOT NULL,                  -- verbatim from the source
  is_key_active   BOOLEAN NOT NULL DEFAULT FALSE,
  source_id       BIGINT NOT NULL REFERENCES data_sources(id),
  source_url      TEXT,
  shade_scope     TEXT,                           -- for colour products the brand lists INCI per shade group; this is the group shown
  PRIMARY KEY (product_id, position)
);

-- Hero ingredients as named by the brand itself (available for every product, unlike full INCI).
CREATE TABLE product_hero_ingredients (
  product_id     BIGINT NOT NULL REFERENCES products(id),
  hero_name      TEXT NOT NULL,                   -- as written in official copy, e.g. 'Salicylic Acid Sphere'
  ingredient_id  BIGINT REFERENCES ingredients(id),
  official_benefit_th TEXT,
  PRIMARY KEY (product_id, hero_name)
);

CREATE TABLE ingredient_interactions (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_a          TEXT NOT NULL,                 -- ingredient_class or INCI name
  class_b          TEXT NOT NULL,
  interaction      TEXT NOT NULL CHECK (interaction IN ('avoid_same_session','introduce_gradually','pairs_well','requires_sunscreen')),
  advice_en        TEXT NOT NULL,
  advice_th        TEXT
);

