-- =====================================================================================
-- Srichand AI Beauty Advisor — prototype database
-- PostgreSQL flavour. `scripts/make_postgres_schema.py`
-- converts it to db/schema.postgres.sql (BIGINT identity keys, TIMESTAMPTZ, JSONB).
--
-- Conventions
--   * BOOLEAN columns hold 0/1 in SQLite.  * TIMESTAMPTZ columns hold ISO-8601 UTC strings.
--   * JSON columns hold JSON text.         * Money is NUMERIC(10,2) in THB unless stated.
--   * Every table is registered in `data_provenance` as real_sourced / derived /
--     curated_knowledge / mock, so nobody mistakes simulated operations for client data.
-- Sections: 0 Meta · 1 Catalogue · 2 Ingredients · 3 Advisor knowledge · 4 Commerce
--           5 Loyalty · 6 Advisor sessions (PDPA) · 7 Views
-- =====================================================================================
-- PostgreSQL 14+ flavour, generated by scripts/05_meta.py from db/schema.sql — do not edit by hand.

-- ───────────────────────────── 0. META ─────────────────────────────
CREATE TABLE data_sources (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          TEXT NOT NULL UNIQUE,            -- e.g. 'srichand_store_api'
  name          TEXT NOT NULL,
  url           TEXT,
  source_type   TEXT NOT NULL CHECK (source_type IN ('official','retailer','third_party_db','regulator','news','curated','internal_mock')),
  accessed_at   TIMESTAMPTZ,
  notes         TEXT
);

CREATE TABLE data_provenance (
  table_name         TEXT PRIMARY KEY,
  origin             TEXT NOT NULL CHECK (origin IN ('real_sourced','derived','curated_knowledge','mock')),
  description        TEXT NOT NULL,
  production_source  TEXT                         -- what system replaces this table in production (ERP, OMS, CRM…)
);

-- ───────────────────────────── 1. CATALOGUE (real, sourced) ─────────────────────────────
CREATE TABLE brands (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug             TEXT NOT NULL UNIQUE,
  name_en          TEXT NOT NULL,
  name_th          TEXT NOT NULL,
  positioning      TEXT,
  target_audience  TEXT,
  price_tier       TEXT CHECK (price_tier IN ('value','mass','masstige')),
  site_url         TEXT,
  source_id        BIGINT REFERENCES data_sources(id)
);

CREATE TABLE product_lines (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_id         BIGINT NOT NULL REFERENCES brands(id),
  slug             TEXT NOT NULL UNIQUE,
  name_en          TEXT NOT NULL,
  name_th          TEXT,
  domain           TEXT NOT NULL CHECK (domain IN ('skincare','sunscreen','powder','base_makeup','colour_makeup','lip','baby','hair','tools','mixed')),
  positioning_en   TEXT,                          -- one-line purpose of the line
  hero_ingredients JSONB,                          -- as named in official copy
  source_id        BIGINT REFERENCES data_sources(id)
);

CREATE TABLE categories (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id   BIGINT REFERENCES categories(id),
  slug        TEXT NOT NULL UNIQUE,
  name_en     TEXT NOT NULL,
  name_th     TEXT,
  sort_order  INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE products (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_id              BIGINT NOT NULL REFERENCES brands(id),
  line_id               BIGINT REFERENCES product_lines(id),
  category_id           BIGINT REFERENCES categories(id),
  slug                  TEXT NOT NULL UNIQUE,
  name_en               TEXT NOT NULL,
  name_th               TEXT NOT NULL,
  product_type          TEXT NOT NULL CHECK (product_type IN ('single','set','gift_with_purchase','accessory','gift_card')),
  lifecycle_status      TEXT NOT NULL CHECK (lifecycle_status IN ('active','legacy','clearance_only')),
  tagline_th            TEXT,                     -- official short description
  description_th        TEXT,                     -- official long description (verbatim, HTML stripped)
  how_to_use            TEXT,                     -- official directions from the product page's how-to-use tab (verbatim)
  summary_en            TEXT,                     -- DERIVED: English summary of the official Thai copy
  texture               TEXT,
  finish                TEXT CHECK (finish IN ('matte','semi_matte','natural','satin','glowy','sheer','tone_up') OR finish IS NULL),
  coverage              TEXT CHECK (coverage IN ('none','sheer','light','medium','medium_to_full','full') OR coverage IS NULL),
  spf_value             TEXT,                     -- '50+', '35' … as printed
  pa_rating             TEXT,                     -- 'PA++++'
  oil_control_hours_claimed INTEGER,              -- official claim, e.g. 'คุมมัน 14 ชั่วโมง' -> 14
  is_water_resistant_claimed BOOLEAN,             -- official copy says กันน้ำ / waterproof
  free_from             JSONB,                     -- official "free from" claims e.g. ["paraben","fragrance"]
  is_fragrance_free     BOOLEAN,                  -- NULL = not stated
  is_alcohol_free       BOOLEAN,
  tested_claims_th      TEXT,                     -- official test footnotes (e.g. irritation test n=32, Dermaproof Asia)
  official_url          TEXT,
  image_url             TEXT,
  review_count_site     INTEGER,
  average_rating_site   NUMERIC(3,2),
  source_id             BIGINT NOT NULL REFERENCES data_sources(id),
  confidence            TEXT NOT NULL CHECK (confidence IN ('official','retailer','third_party','unverified')),
  verified_at           TIMESTAMPTZ NOT NULL,
  curation_notes        TEXT
);
CREATE INDEX idx_products_brand ON products(brand_id);
CREATE INDEX idx_products_line ON products(line_id);
CREATE INDEX idx_products_category ON products(category_id);

-- Every purchasable SKU (a size × shade, a sachet box, a multipack, a set) is one variant row.
CREATE TABLE product_variants (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id          BIGINT NOT NULL REFERENCES products(id),
  sku                 TEXT NOT NULL UNIQUE,       -- official SKU from the site
  variant_label       TEXT NOT NULL,              -- '30 ml', '9 g · 120 Beige', 'Box of 6 × 10 ml sachets'
  pack_format         TEXT NOT NULL CHECK (pack_format IN ('full_size','mini','sachet','sachet_box','multipack','set','gift','other')),
  units_per_pack      INTEGER NOT NULL DEFAULT 1,
  size_value          NUMERIC(8,2),
  size_unit           TEXT CHECK (size_unit IN ('ml','g') OR size_unit IS NULL),
  shade_code          TEXT,
  shade_name          TEXT,
  shade_undertone     TEXT CHECK (shade_undertone IN ('cool_pink','neutral','warm_yellow','warm_golden','peach','corrector') OR shade_undertone IS NULL),  -- DERIVED from official shade name
  shade_depth_rank    INTEGER,                    -- DERIVED: 1 = lightest within the product (from official shade numbering)
  shade_guidance_th   TEXT,                       -- official 'suits which skin tone' line, verbatim, where published
  list_price          NUMERIC(10,2) NOT NULL,     -- official regular price (THB)
  sale_price          NUMERIC(10,2),              -- official current price if discounted, else NULL
  currency            TEXT NOT NULL DEFAULT 'THB',
  web_in_stock        BOOLEAN NOT NULL,           -- srichand.com availability flag at snapshot time (real)
  is_listed_on_site   BOOLEAN NOT NULL DEFAULT TRUE,
  site_listing_id     BIGINT,
  site_variation_id   BIGINT,
  barcode             TEXT,                       -- not published; NULL until client master data is loaded
  price_checked_at    TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_variants_product ON product_variants(product_id);

CREATE TABLE bundle_components (
  bundle_variant_id     BIGINT NOT NULL REFERENCES product_variants(id),
  component_variant_id  BIGINT REFERENCES product_variants(id),   -- NULL when the component is not sold separately
  component_product_id  BIGINT REFERENCES products(id),
  component_label       TEXT NOT NULL,
  quantity              INTEGER NOT NULL DEFAULT 1,
  is_free_gift          BOOLEAN NOT NULL DEFAULT FALSE,
  PRIMARY KEY (bundle_variant_id, component_label)
);

