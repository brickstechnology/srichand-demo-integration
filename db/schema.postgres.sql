-- ───────────────────────────── 7. VIEWS (what the agent tools read) ─────────────────────────────
CREATE VIEW v_variant_catalog AS
SELECT v.id AS variant_id, v.sku, p.id AS product_id, b.name_en AS brand, l.name_en AS line,
       c.name_en AS category, p.name_en, p.name_th, p.product_type, p.lifecycle_status,
       v.variant_label, v.pack_format, v.size_value, v.size_unit, v.shade_code, v.shade_name,
       v.list_price, v.sale_price, COALESCE(v.sale_price, v.list_price) AS current_price,
       v.web_in_stock, v.is_listed_on_site, p.official_url, p.image_url
FROM product_variants v
JOIN products p ON p.id = v.product_id
JOIN brands b ON b.id = p.brand_id
LEFT JOIN product_lines l ON l.id = p.line_id
LEFT JOIN categories c ON c.id = p.category_id;

CREATE VIEW v_stock_available AS
SELECT i.variant_id, SUM(i.qty_on_hand - i.qty_reserved) AS qty_available,
       SUM(CASE WHEN w.serves = 'online_orders' THEN i.qty_on_hand - i.qty_reserved ELSE 0 END) AS qty_available_online
FROM inventory i JOIN warehouses w ON w.id = i.warehouse_id
GROUP BY i.variant_id;

CREATE VIEW v_gap_demand AS
SELECT g.slug AS gap, g.title_en, g.severity, COUNT(e.id) AS events,
       COUNT(DISTINCT e.customer_id) AS distinct_customers, MIN(e.created_at) AS first_seen, MAX(e.created_at) AS last_seen
FROM range_gaps g LEFT JOIN range_gap_events e ON e.gap_id = g.id
GROUP BY g.id, g.slug, g.title_en, g.severity;

CREATE VIEW v_customer_360 AS
SELECT cu.id AS customer_id, cu.line_user_id, cu.line_display_name, cu.first_name, t.name AS tier,
       la.points_balance, la.spend_this_period,
       (SELECT COUNT(*) FROM orders o WHERE o.customer_id = cu.id AND o.status NOT IN ('cancelled','refunded')) AS order_count,
       (SELECT MAX(o.placed_at) FROM orders o WHERE o.customer_id = cu.id) AS last_order_at,
       (SELECT MAX(s.created_at) FROM face_analysis_sessions s WHERE s.customer_id = cu.id) AS last_analysis_at
FROM customers cu
LEFT JOIN loyalty_accounts la ON la.customer_id = cu.id
LEFT JOIN loyalty_tiers t ON t.id = la.tier_id;
